bool is_valid_pdf(const PDF<float>& pdf, float tol = 1e-6) {
    if (pdf.size() == 0) {
        //printf("PDF IS 0\n");
        return false;}

    float sum = 0.0f;
    for (int i = 0; i < pdf.size(); ++i) {
        if (pdf[i] < 0) return false;

             // all elements must be non-negative
        sum += pdf[i];
    }

    return std::abs(sum - 1.0) < tol;  // sum must be ~1
}
